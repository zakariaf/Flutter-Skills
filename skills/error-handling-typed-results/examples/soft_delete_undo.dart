// Optimistic soft-delete with a SnackBar Undo, plus the shared filtered read.
// The row is never hard-deleted on tap: it flips is_deleted=1 and fails the
// shared is_deleted=0 filter, so it disappears from EVERY read surface at once
// (lists, analytics, rollups, charts). Undo just clears the flag.
//
// Neutral domain (Task). Uses Drift + Riverpod. The single shared filter is the
// load-bearing invariant: no read may roll its own WHERE is_deleted clause.

import 'package:clock/clock.dart';
import 'package:drift/drift.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

// --- The ONE shared filter every active read composes ------------------------
// A Drift view is the alternative:
//   CREATE VIEW tasks_active AS SELECT * FROM tasks WHERE is_deleted = 0;

extension ActiveOnly on $TasksTable {
  Expression<bool> get active => isDeleted.equals(false);
}

class TaskDao extends DatabaseAccessor<AppDatabase> {
  TaskDao(super.db);

  // Lists, analytics, rollups, and chart datasets ALL read through this.
  Future<List<Task>> activeTasks(String accountId) =>
      (select(tasks)..where((t) => t.accountId.equals(accountId) & t.active)).get();

  Future<void> softDelete(String id, {required DateTime at}) =>
      (update(tasks)..where((t) => t.id.equals(id)))
          .write(TasksCompanion(isDeleted: const Value(true), deletedAt: Value(at)));

  Future<void> restore(String id) => (update(tasks)..where((t) => t.id.equals(id)))
      .write(const TasksCompanion(isDeleted: Value(false), deletedAt: Value(null)));
}

// --- Optimistic delete + SnackBar Undo via Riverpod --------------------------

class TasksNotifier extends Notifier<void> {
  @override
  void build() {}

  Future<void> delete(BuildContext context, String id) async {
    final l10n = AppLocalizations.of(context);
    final dao = ref.read(taskDaoProvider);

    await dao.softDelete(id, at: clock.now().toUtc()); // package:clock
    ref.invalidate(activeTasksProvider); // list drops the row immediately (optimistic)

    if (!context.mounted) return; // guard BuildContext after the await
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(l10n.recordDeleted),
        action: SnackBarAction(
          label: l10n.undo,
          onPressed: () async {
            await dao.restore(id); // clears is_deleted/deleted_at — exact restore
            ref.invalidate(activeTasksProvider);
          },
        ),
      ),
    );
  }
}

